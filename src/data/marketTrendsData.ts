/**
 * Machine Learning Recommendation Function
 * Learns from live demand volume, buyer count, seasonal pricing trends, and farmer land inputs
 */
export function calculateCustomCropRecommendation(
  soilType: string,
  waterSource: string,
  landAcre: number
): {
  topSuggestions: MLCropSuggestion[];
  totalProjectedRevenue: number;
  totalProjectedProfit: number;
  totalUnmetDemandTonnes: number;
} {
  const filtered = ML_CROP_SUGGESTIONS.map((crop) => {
    let score = crop.mlDemandScore;

    // Soil compatibility modifier
    const soilMatch = crop.soilSuitability.some((s) =>
      s.toLowerCase().includes(soilType.toLowerCase()) || soilType.toLowerCase().includes('all')
    );
    if (!soilMatch) score -= 8;

    // Water compatibility modifier
    if (waterSource === 'Low / Rainfed' && crop.waterRequirement === 'High') {
      score -= 15;
    } else if (waterSource === 'Borewell / Drip' && crop.waterRequirement === 'Low') {
      score += 3;
    }

    return {
      ...crop,
      mlDemandScore: Math.min(99, Math.max(50, score)),
    };
  }).sort((a, b) => b.mlDemandScore - a.mlDemandScore);

  const topCrop = filtered[0];
  const acres = landAcre || 1;
  const totalProjectedRevenue = (topCrop.projectedNetProfitPerAcre + topCrop.estimatedCostOfCultivationPerAcre) * acres;
  const totalProjectedProfit = topCrop.projectedNetProfitPerAcre * acres;
  const totalUnmetDemandTonnes = Math.round(
    filtered.reduce((sum, c) => sum + c.unmetDemandKg, 0) / 1000
  );

  return {
    topSuggestions: filtered,
    totalProjectedRevenue,
    totalProjectedProfit,
    totalUnmetDemandTonnes,
  };
}
